// Marginalia · 3D asset pipeline (plan 1.6).
//
//   assets-src/3d/*.glb        originals (kept outside Git, see .gitignore)
//   assets-src/textures/<set>/ 1K JPG surface maps
//   -> public/3d/<name>.<hash>.glb         WebP textures, meshopt-compressed, no simplification
//   -> public/textures/<set>/<map>.<hash>.jpg
//   -> src/three/asset-manifest.generated.ts  logical name -> hashed URL (committed)
//
// Texture size caps: interactive objects 2048, furniture 1024, small props 512.
// Hashed file names let Vercel serve them with `Cache-Control: immutable` (see vercel.json).
//
//   node scripts/optimize-assets.mjs [--only=<glb basename>]
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';
import { dedup, meshopt, prune, textureCompress } from '@gltf-transform/functions';
import { MeshoptEncoder } from 'meshoptimizer';
import sharp from 'sharp';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SRC_3D = join(root, 'assets-src/3d');
const SRC_TEX = join(root, 'assets-src/textures');
const OUT_3D = join(root, 'public/3d');
const OUT_TEX = join(root, 'public/textures');
const MANIFEST = join(root, 'src/three/asset-manifest.generated.ts');

// Models the app loads. Anything else in assets-src/3d is NOT published (unused or licence-blocked).
const MODELS = {
  // interactive objects
  antique_globe: 2048, macbook: 2048, wooden_picture_frame: 2048, messy_tack_board: 2048,
  book: 2048,
  // furniture (the two big bookshelves are scenery; their clicks need no texture detail)
  book_shelf: 512, 'bookshelf real': 1024,
  iron_art_storage_bookshelf: 1024, lounge_chair: 1024, chair: 1024, floor_lamp: 1024,
  // small props
  bamboo_with_plant_pot: 512, roomlight: 512, book_open: 1024,
};

const only = process.argv.find((a) => a.startsWith('--only='))?.slice(7);
const hash8 = (buf) => createHash('sha256').update(buf).digest('hex').slice(0, 8);
const mb = (n) => (n / 1024 / 1024).toFixed(2);

await MeshoptEncoder.ready;
const io = new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({ 'meshopt.encoder': MeshoptEncoder });

mkdirSync(OUT_3D, { recursive: true });
if (!only) for (const f of readdirSync(OUT_3D)) if (f.endsWith('.glb')) rmSync(join(OUT_3D, f));

const modelUrls = {};
let totalIn = 0;
let totalOut = 0;

for (const [name, texSize] of Object.entries(MODELS)) {
  if (only && only !== name) continue;
  const input = join(SRC_3D, `${name}.glb`);
  if (!existsSync(input)) throw new Error(`missing source ${input}`);
  const doc = await io.read(input);
  await doc.transform(
    dedup(),
    prune(),
    textureCompress({ encoder: sharp, targetFormat: 'webp', resize: [texSize, texSize], quality: 78 }),
    meshopt({ encoder: MeshoptEncoder, level: 'medium' }), // quantize + compress; no simplification
  );
  const bytes = await io.writeBinary(doc);
  const file = `${name.replace(/\s+/g, '_')}.${hash8(bytes)}.glb`;
  writeFileSync(join(OUT_3D, file), bytes);
  modelUrls[name] = `3d/${file}`;
  totalIn += statSync(input).size;
  totalOut += bytes.length;
  process.stdout.write(`${name.padEnd(30)} ${mb(statSync(input).size).padStart(7)} MB -> ${mb(bytes.length).padStart(6)} MB  (tex ≤ ${texSize})\n`);
}
process.stdout.write(`models total ${mb(totalIn)} MB -> ${mb(totalOut)} MB\n`);

// Surface textures: <set>/<map>.jpg -> 1K, hashed.
const textureUrls = {};
if (!only && existsSync(SRC_TEX)) {
  if (existsSync(OUT_TEX)) rmSync(OUT_TEX, { recursive: true, force: true });
  for (const set of readdirSync(SRC_TEX).filter((d) => statSync(join(SRC_TEX, d)).isDirectory())) {
    for (const file of readdirSync(join(SRC_TEX, set)).filter((f) => f.endsWith('.jpg'))) {
      const out = await sharp(join(SRC_TEX, set, file))
        .resize({ width: 1024, height: 1024, fit: 'inside', withoutEnlargement: true })
        .jpeg({ quality: 82, mozjpeg: true })
        .toBuffer();
      const map = basename(file, '.jpg');
      const outName = `${map}.${hash8(out)}.jpg`;
      mkdirSync(join(OUT_TEX, set), { recursive: true });
      writeFileSync(join(OUT_TEX, set, outName), out);
      textureUrls[`${set}/${map}`] = `textures/${set}/${outName}`;
      process.stdout.write(`texture ${set}/${map}  ${mb(out.length)} MB\n`);
    }
  }
}

if (!only) {
  const body = (obj) => Object.entries(obj).sort().map(([k, v]) => `  '${k}': '${v}',`).join('\n');
  writeFileSync(MANIFEST, `// GENERATED by scripts/optimize-assets.mjs — do not edit.\n// Logical name -> content-hashed path under public/ (resolve with asset()).\n\nexport const MODEL_PATHS = {\n${body(modelUrls)}\n} as const;\n\nexport const TEXTURE_PATHS = {\n${body(textureUrls)}\n} as const;\n`);
  process.stdout.write(`wrote ${MANIFEST.replace(root + '/', '')}\n`);
}
